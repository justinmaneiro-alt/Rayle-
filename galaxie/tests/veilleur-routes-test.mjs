// Test des routes locales /__veilleur/… (serveur reel sur un port libre, dossier temporaire). Aucun reseau, aucun Telegram.
// Lancer :  node galaxie/tests/veilleur-routes-test.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dossier = fs.mkdtempSync(path.join(os.tmpdir(), 'veilleur-routes-'));
process.env.RAYLE_VEILLEUR_DOSSIER = dossier;
const { creerServeur } = await import('../../serveur.mjs');
let ok = 0, ko = 0;
const v = (n, c, d = '') => { c ? ok++ : ko++; if (!c) console.log('KO  ' + n + (d !== '' ? ' — ' + d : '')); };
const srv = creerServeur(); await new Promise(r => srv.listen(0, '127.0.0.1', r));
const base = 'http://127.0.0.1:' + srv.address().port;
const get = p => fetch(base + p).then(async r => ({ s: r.status, j: await r.json() }));
const post = (p, corps, entetes = { 'X-Rayle-Multi': '1' }) => fetch(base + p, { method: 'POST', headers: { 'Content-Type': 'application/json', ...entetes }, body: JSON.stringify(corps) }).then(async r => ({ s: r.status, j: await r.json() }));

let r = await get('/__veilleur/etat');
v('etat : veilleur arrete, reglages par defaut desactives', r.s === 200 && r.j.enMarche === false && r.j.reglages.actif === false && r.j.workerConfigure === false);
r = await post('/__veilleur/reglages', { patch: { actif: true, maxParJour: 3, types: { OBSERVATION: true } } });
v('reglages : enregistres et bornes', r.j.ok && r.j.reglages.actif && r.j.reglages.maxParJour === 3 && r.j.reglages.types.OBSERVATION);
r = await post('/__veilleur/reglages', { patch: { maxParJour: 9999 } });
v('reglages : la valeur precedente est conservee, la nouvelle est bornee', r.j.reglages.maxParJour === 50 && r.j.reglages.actif === true);
r = await post('/__veilleur/reglages', { patch: { actif: true } }, {});
v('POST sans en-tete dedie : refuse', r.s === 403);
const rBad = await fetch(base + '/__veilleur/etat', { headers: { Host: 'evil.example' } }).catch(() => null);
r = await post('/__veilleur/ms-etat', { strategies: [{ id: 'ms1', nom: 'Test', strategie: { cote: 'long' }, confiance: { etiquette: 'NON VALIDÉE', phrase: 'x' } }] });
v('ms-etat : les stratégies en alertes sont enregistrées pour le Veilleur', r.s === 200 && r.j.ok && r.j.n === 1 && fs.existsSync(path.join(dossier, 'ms-strategies.json')));
r = await post('/__veilleur/ms-etat', { strategies: [{ id: 5 }] });
v('ms-etat : une liste invalide est refusée', r.s === 400);
r = await post('/__veilleur/ms-etat', { strategies: [{ id: 'a', strategie: {}, confiance: { etiquette: 'X' } }] }, {});
v('ms-etat : sans en-tête dédié, refusé', r.s === 403);
r = await post('/__veilleur/config', { url: 'http://worker.test', jeton: 'x' });
v('config : http refuse', r.s === 400);
r = await post('/__veilleur/config', { url: 'https://rayle.exemple.workers.dev', jeton: 'rd_FAUXJETON_TEST_123' });
v('config : enregistree', r.j.ok);
r = await get('/__veilleur/etat');
v('etat : worker configure, jamais le jeton', r.j.workerConfigure === true && !JSON.stringify(r.j).includes('FAUXJETON'));
r = await post('/__veilleur/strategie', { verdict: { etat: 'validee', strategie: {} }, nVariantes: 12 });
v('strategie : enregistree', r.j.ok && JSON.parse(fs.readFileSync(path.join(dossier, 'strategie.json'), 'utf8')).verdict.etat === 'validee');
r = await post('/__veilleur/strategie', { verdict: 5 });
v('strategie : verdict invalide refuse', r.s === 400);
fs.writeFileSync(path.join(dossier, 'alertes.jsonl'), JSON.stringify({ id: 'a', type: 'MACRO', t: 1000, texte: 'x' }) + '\n' + JSON.stringify({ id: 'b', type: 'ENTREE', t: 2000, texte: 'y' }) + '\n');
r = await get('/__veilleur/alertes?depuis=1500');
v('alertes : seulement les plus recentes', r.j.alertes.length === 1 && r.j.alertes[0].id === 'b');
r = await post('/__veilleur/arreter', {});
v('arret : fichier de demande ecrit', r.j.ok && fs.existsSync(path.join(dossier, 'arret.demande')));
r = await get('/__veilleur/inconnue');
v('route inconnue : 404', r.s === 404);
srv.close();
console.log(ok + ' ok, ' + ko + ' ko'); process.exit(ko ? 1 : 0);
